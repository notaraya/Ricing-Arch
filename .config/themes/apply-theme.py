#!/usr/bin/env python3
import os
import re
import tempfile
from pathlib import Path

HOME = Path.home()
PALETTE = HOME / ".config/themes/themes.txt"

def write_atomic(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".theme-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(content)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)

def main():
    colors = [x.strip().upper() for x in PALETTE.read_text().splitlines()
              if x.strip()]
    if len(colors) != 16 or any(
        not re.fullmatch(r"#[0-9A-F]{6}", x) for x in colors
    ):
        raise SystemExit("themes.txt must contain exactly 16 #RRGGBB colors")

    c = colors

    # Shared semantic roles. All values come from themes.txt.
    role = {
        "bg": c[7],
        "bg_deep": c[10],
        "surface": c[8],
        "surface_raised": c[9],
        "surface_alt": c[11],
        "fg": c[15],
        "fg_muted": c[4],
        "accent": c[0],
        "accent_strong": c[2],
        "accent_soft": c[3],
        "secondary": c[5],
        "highlight": c[15],
        "selection": c[2],
        "border": c[12],
    }

    # GTK 3 and GTK 4 CSS. We own these generated files.
    css = f"""/* Generated by apply-theme.py; do not edit manually. */
@define-color accent_color {role['accent']};
@define-color accent_bg_color {role['accent_strong']};
@define-color accent_fg_color {role['highlight']};
@define-color window_bg_color {role['bg']};
@define-color window_fg_color {role['fg']};
@define-color view_bg_color {role['surface']};
@define-color view_fg_color {role['fg']};
@define-color headerbar_bg_color {role['surface_raised']};
@define-color headerbar_fg_color {role['fg']};
@define-color card_bg_color {role['surface_alt']};
@define-color dialog_bg_color {role['bg']};
@define-color popover_bg_color {role['surface_raised']};
@define-color theme_bg_color {role['bg']};
@define-color theme_fg_color {role['fg']};
@define-color theme_base_color {role['surface']};
@define-color theme_text_color {role['fg']};
@define-color theme_selected_bg_color {role['selection']};
@define-color theme_selected_fg_color {role['highlight']};

window, dialog, .background {{
  background-color: @theme_bg_color;
  color: @theme_fg_color;
}}
entry, textview text, view, list, row {{
  background-color: @theme_base_color;
  color: @theme_text_color;
}}
selection, text selection {{
  background-color: @theme_selected_bg_color;
  color: @theme_selected_fg_color;
}}
button.suggested-action, button:checked {{
  background-color: @accent_bg_color;
  color: @accent_fg_color;
}}
"""
    write_atomic(HOME / ".config/gtk-3.0/gtk.css", css)
    # Keep Hyprland's generated GTK 4 stylesheet connected.
    gtk4_path = HOME / ".config/gtk-4.0/gtk.css"
    gtk4_import = '@import url("hyprland-colors.css");'
    gtk4_css = gtk4_import + "\n" + css
    write_atomic(gtk4_path, gtk4_css)

    # Qt6ct uses 21 or 22 comma-separated QPalette colors.
    # Use 22 entries, including Accent for recent Qt versions.
    def argb(value):
        return "#ff" + value[1:].lower()

    active = [
        role["fg"], role["surface_raised"], c[15], c[12],
        c[10], c[13], role["fg"], role["highlight"],
        role["fg"], role["surface"], role["bg"], role["bg_deep"],
        role["selection"], role["highlight"], role["accent"],
        c[4], role["surface_alt"], role["fg"],
        role["surface_raised"], role["fg"], c[4], role["accent"],
    ]
    disabled = [
        c[4], role["surface_raised"], c[12], c[13],
        role["bg_deep"], c[13], c[4], c[15],
        c[4], role["surface"], role["bg"], role["bg_deep"],
        c[12], role["bg"], c[4], c[4],
        role["surface_alt"], c[4], role["surface_raised"],
        c[4], c[4], c[12],
    ]
    inactive = active.copy()

    qt = "[ColorScheme]\n"
    qt += "active_colors=" + ", ".join(map(argb, active)) + "\n"
    qt += "inactive_colors=" + ", ".join(map(argb, inactive)) + "\n"
    qt += "disabled_colors=" + ", ".join(map(argb, disabled)) + "\n"
    write_atomic(HOME / ".config/qt6ct/colors/our-theme.conf", qt)

    # Kitty: terminal base colors and all 16 palette slots.
    kitty = f"""# Generated by apply-theme.py; do not edit manually.
foreground {role['fg']}
background {role['bg']}
selection_foreground {role['fg']}
selection_background {role['selection']}
cursor {role['highlight']}
"""
    for i, color in enumerate(c):
        kitty += f"color{i} {color}\n"
    write_atomic(HOME / ".config/kitty/theme.conf", kitty)

    # Rofi palette variables; import this file from config.rasi.
    rofi = f"""/* Generated by apply-theme.py; import from config.rasi. */
* {{
    background: {role['bg']};
    background-alt: {role['surface_raised']};
    foreground: {role['fg']};
    selected: {role['selection']};
    active: {role['accent']};
    urgent: {role['accent_strong']};
    border-color: {role['border']};
}}
"""
    write_atomic(
        HOME / ".config/rofi/themes/generated-palette.rasi", rofi
    )

        # Waybar palette. Generated from the same 16-color source.
        # Colors 1-7: accents
        # Colors 8-11: backgrounds
        # Colors 12-15: extras, available but not used by default
        # Color 16: highlight
    waybar = "/* Generated by apply-theme.py; do not edit manually. */\n"

    for i in range(7):
        waybar += f"@define-color accent{i + 1} {c[i]};\n"

    for i in range(4):
        waybar += f"@define-color background{i + 1} {c[i + 7]};\n"

    for i in range(4):
        waybar += f"@define-color extra{i + 1} {c[i + 11]};\n"

    waybar += f"@define-color highlight {c[15]};\n"

        # Compatibility with the existing Waybar stylesheet
    waybar += "@define-color foreground @accent1;\n"
    waybar += "@define-color background @background1;\n"

    write_atomic(HOME / ".config/waybar/waybar-colors.css", waybar)

    print("Generated GTK 3, GTK 4, Qt6ct, Kitty and Rofi theme files.")
    print("Palette source: " + str(PALETTE))
    print("All 16 palette colors were preserved.")

if __name__ == "__main__":
    main()
