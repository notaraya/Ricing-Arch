local function mkdir(path)
    os.execute("mkdir -p " .. string.format("%q", path))
end

local function read_file(path)
    local f = io.open(path, "r")
    if not f then return nil end
    local data = f:read("*a")
    f:close()
    return data
end

local function write_file(path, data)
    local f, write_err = io.open(path, "w")
    if not f then
        error("Cannot write " .. path .. ": " .. tostring(write_err))
    end

    f:write(data)
    f:close()
end

local function sha256(data)
    mkdir(STATE_DIR)

    local tmp = STATE_DIR .. "/palette.tmp"
    write_file(tmp, data)

    local pipe = io.popen(
        "sha256sum " .. string.format("%q", tmp) .. " 2>/dev/null"
    )

    if not pipe then
        os.remove(tmp)
        error("Could not run sha256sum")
    end

    local result = pipe:read("*l")
    pipe:close()
    os.remove(tmp)

    return result and result:match("^(%x+)")
end

