local function configure_system_theme()
    -- Prefer dark mode where the desktop settings service supports it.
    -- This does not change GTK theme names, icons, cursors or borders.
    os.execute(
        "gsettings set org.gnome.desktop.interface color-scheme " ..
        "'prefer-dark' >/dev/null 2>&1"
    )
end

