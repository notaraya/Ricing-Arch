local function make_gtk_css()
    local t = theme

    return table.concat({
        "/* Generated by hyprland.lua; do not edit manually. */",
        "@define-color theme_bg_color " .. t.background .. ";",
        "@define-color theme_base_color " .. t.background .. ";",
        "@define-color theme_fg_color " .. t.foreground .. ";",
        "@define-color theme_text_color " .. t.foreground .. ";",
        "@define-color accent_color " .. t.accents[1] .. ";",
        "@define-color accent_bg_color " .. t.accents[1] .. ";",
        "@define-color accent_fg_color " .. t.background .. ";",
        "@define-color selected_bg_color " .. t.selection .. ";",
        "@define-color selected_fg_color " .. t.foreground .. ";",
        "",
        "/* General application backgrounds */",
        "window, dialog, .background {",
        "  background-color: @theme_bg_color;",
        "  color: @theme_fg_color;",
        "}",
        "",
        "/* Inputs and content areas */",
        "entry, textview text, view, list, row {",
        "  background-color: " .. t.surface_light .. ";",
        "  color: @theme_text_color;",
        "}",
        "",
        "/* Secondary surfaces */",
        "popover, menu, .popover, .menu {",
        "  background-color: " .. t.surface_mid .. ";",
        "  color: @theme_fg_color;",
        "}",
        "",
        "/* Accent states */",
        "button:checked, button.suggested-action,",
        "selection, text selection {",
        "  background-color: @selected_bg_color;",
        "  color: @selected_fg_color;",
        "}",
        "",
        "link, .link { color: " .. t.accents[4] .. "; }",
        "",
        "/* Intentionally no border-color or border rules. */",
        "",
    }, "\n")
end

local function install_gtk_css(directory, css)
    mkdir(directory)

    write_file(directory .. "/hyprland-colors.css", css)

    local main = directory .. "/gtk.css"
    local existing = read_file(main) or ""
    local import = '@import url("hyprland-colors.css");'
    local kept = {}

    -- Avoid duplicate imports when rerunning.
    for line in (existing .. "\n"):gmatch("(.-)\n") do
        if line:match("^%s*@import") == nil
            or line:find("hyprland-colors.css", 1, true) == nil then
            kept[#kept + 1] = line
        end
    end

    -- CSS imports must come before ordinary rules.
    write_file(main, import .. "\n" .. table.concat(kept, "\n"))
end

