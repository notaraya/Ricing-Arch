local function argb(hex)
    -- Qt color roles use ARGB notation.
    return "#FF" .. hex:sub(2)
end

local function make_qt_colors()
    local t = theme
    local a = t.accents

    local roles = {
        argb(t.foreground),       -- WindowText
        argb(t.surface_light),    -- Button
        argb(a[7]),               -- Light
        argb(a[6]),               -- Midlight
        argb(t.secondary_deep),   -- Dark
        argb(t.secondary_dark),   -- Mid
        argb(t.foreground),       -- Text
        argb(t.highlight),        -- BrightText
        argb(t.foreground),       -- ButtonText
        argb(t.background),       -- Base
        argb(t.background),       -- Window
        argb(t.secondary_deep),   -- Shadow
        argb(t.selection),        -- Highlight
        argb(t.foreground),       -- HighlightedText
        argb(a[4]),               -- Link
        argb(a[5]),               -- LinkVisited
        argb(t.surface_mid),      -- AlternateBase
        argb(t.surface_light),    -- ToolTipBase
        argb(t.foreground),       -- ToolTipText
        argb(t.secondary_light),  -- PlaceholderText
        argb(a[1]),               -- Accent
        argb(a[2]),               -- Extra role
    }

    local value = table.concat(roles, ", ")

    return table.concat({
        "# Generated by hyprland.lua",
        "[ColorScheme]",
        "active_colors=" .. value,
        "inactive_colors=" .. value,
        "disabled_colors=" .. value,
        "",
    }, "\n")
end

local function set_ini_key(content, section, key, value)
    local lines = {}

    for line in (content .. "\n"):gmatch("(.-)\n") do
        lines[#lines + 1] = line
    end

    local current_section = nil
    local section_found = false
    local key_found = false
    local insert_at = nil

    for i, line in ipairs(lines) do
        local section_name = line:match("^%s*%[([^%]]+)%]%s*$")

        if section_name then
            if current_section == section and not key_found then
                insert_at = i
            end

            current_section = section_name

            if section_name == section then
                section_found = true
            end
        elseif current_section == section then
            local existing_key = line:match("^%s*([^=]+)%s*=")

            if existing_key and existing_key:match("^%s*(.-)%s*$") == key then
                lines[i] = key .. "=" .. value
                key_found = true
            end
        end
    end

    if key_found then
        return table.concat(lines, "\n")
    end

    if not section_found then
        lines[#lines + 1] = ""
        lines[#lines + 1] = "[" .. section .. "]"
        lines[#lines + 1] = key .. "=" .. value
    else
        table.insert(lines, insert_at or (#lines + 1), key .. "=" .. value)
    end

    return table.concat(lines, "\n")
end

local function configure_qt6()
    mkdir(QT_DIR)
    mkdir(QT_COLORS_DIR)

    local scheme_path = QT_COLORS_DIR .. "/hyprland.conf"
    write_file(scheme_path, make_qt_colors())

    local config_path = QT_DIR .. "/qt6ct.conf"
    local config = read_file(config_path) or ""

    config = set_ini_key(
        config, "Appearance", "color_scheme_path", scheme_path
    )
    config = set_ini_key(
        config, "Appearance", "custom_palette", "true"
    )

    write_file(config_path, config)
end

