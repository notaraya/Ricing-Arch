local function apply_theme()
    local fingerprint = sha256(table.concat(palette, "\n"))

    if not fingerprint then
        error("Failed to calculate palette checksum")
    end

    local state_file = STATE_DIR .. "/palette.sha256"
    local previous = read_file(state_file)

    if previous and previous:match("^%s*(.-)%s*$") == fingerprint then
        print("Wallpaper palette unchanged; skipping theme generation.")
        return
    end

    local css = make_gtk_css()

    install_gtk_css(CONFIG .. "/gtk-3.0", css)
    install_gtk_css(CONFIG .. "/gtk-4.0", css)

    configure_qt6()
    configure_system_theme()

    write_file(state_file, fingerprint .. "\n")

    print("Wallpaper theme updated.")
    print("GTK 3 CSS generated.")
    print("GTK 4 CSS generated.")
    print("Qt 6 qt6ct color scheme generated.")
    print("Hyprland borders have not been changed.")
end

apply_theme()




