local function read_colors(input_path)
    local input, err = io.open(input_path, "r")
    if not input then
        return nil, err
    end

    local colors = {}

    for line in input:lines() do
        local color = line:match("^%s*(.-)%s*$")

        if color ~= "" then
            if not color:match("^#%x%x%x%x%x%x$") then
                input:close()
                return nil, "Invalid color: " .. color
            end

            table.insert(colors, color:upper())
        end
    end

    input:close()

    if #colors ~= 16 then
        return nil, "Expected 16 colors, found " .. #colors
    end

    return colors
end

-- Keep your existing Hyprland color format.
local function to_rgba(hex)
    return "rgba(" .. hex:sub(2) .. "ff)"
end

